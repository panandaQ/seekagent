from __future__ import annotations

from config import settings


def _build_fields_section() -> str:
    """动态构建字段提取说明"""
    if not settings.fields:
        return """提取以下字段：
1. 个人简介：教育背景、工作经历、主要成就
2. 所属单位：完整机构名称
3. 邮箱：公开邮箱地址
4. 电话：公开办公电话"""

    lines = ["当你到达包含专家详细信息的页面时，提取以下字段："]
    for i, field in enumerate(settings.fields, 1):
        lines.append(f"{i}. {field.label}：{field.description}")
    return "\n".join(lines)



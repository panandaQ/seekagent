def build_task_prompt(expert_name: str, affiliation: str = "", queries: list[str] | None = None) -> str:
    """构建任务提示词，字段说明从配置动态生成"""
    search_queries = list(queries) if queries is not None else []
    while len(search_queries) < 3:
        search_queries.append(f"{expert_name} 计算机科学 学者")

    fields_section = _build_fields_section()

    # 处理 affiliation：空字符串时不显示"未知"
    affiliation_display = affiliation.strip() if affiliation else None
    affiliation_line = f"- 已知单位：{affiliation_display}" if affiliation_display else ""
    # 用于搜索的单位（有值则加空格，无值则为空）
    affiliation_for_search = f" {affiliation_display}" if affiliation_display else ""

    return TASK_PROMPT_TEMPLATE.format(
        expert_name=expert_name,
        affiliation_line=affiliation_line,
        affiliation=affiliation_for_search,
        query_1=search_queries[0],
        query_2=search_queries[1],
        query_3=search_queries[2],
        fields_section=fields_section,
    )
